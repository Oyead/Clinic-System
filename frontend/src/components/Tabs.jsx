export function PanelTabs({ tabs, active, onChange, label }) {
  return (
    <div className="tabs" role="tablist" aria-label={label || 'Dashboard sections'}>
      {tabs.map((t) => (
        <button
          key={t.id}
          type="button"
          role="tab"
          aria-selected={active === t.id}
          className={`tab${active === t.id ? ' active' : ''}`}
          onClick={() => onChange(t.id)}
        >
          {t.label}
        </button>
      ))}
    </div>
  );
}
